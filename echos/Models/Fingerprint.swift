//  Как показывать адрес человеку.
//
//  Вся защита держится на том, что адрес — отпечаток ключа — у человека
//  один, где бы он ни был. Но пока адрес невидим, посредника заметить
//  нельзя в принципе: единственный способ — сверить то, что показывает
//  ваш экран, с тем, что показывает его. Значит, адрес должен быть на
//  экране и читаться вслух: шестнадцать знаков подряд для этого не годятся,
//  четыре группы по четыре — уже да.
//

import Foundation

enum Fingerprint {

    /// Отпечаток группами по четыре знака: `93f4 40ee 4f07 d563`.
    ///
    /// Всё, что не похоже на отпечаток, отдаётся как есть: в тестах адресом
    /// служат произвольные строки, и ломать их разбиением незачем.
    static func display(_ address: String) -> String {
        guard address.count == 16, address.allSatisfy(\.isHexDigit) else {
            return address
        }

        return stride(from: 0, to: 16, by: 4)
            .map { offset -> Substring in
                let start = address.index(address.startIndex, offsetBy: offset)
                return address[start..<address.index(start, offsetBy: 4)]
            }
            .joined(separator: " ")
    }

    /// Что сказать человеку, который видит адрес впервые.
    static let howToCheck = "У собеседника на главном экране свой адрес. "
        + "Сверьте: он должен совпасть с тем, что показывает ваш телефон в его чате. "
        + "Разные адреса — значит, между вами кто-то есть."
}
