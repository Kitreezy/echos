//  Пять пантонов и нейтральная шкала. Пантоны насыщенные, и если раскрасить
//  ими экраны, получится витраж, а не покой. Поэтому основную площадь держат
//  нейтрали, а цвет появляется точечно — см. Theme.
//

import Foundation

enum Palette {

    // MARK: - Pantone

    /// Blue 072 C. Единственная по-настоящему яркая точка в интерфейсе.
    static let blue072 = "#10069F"

    /// 18-1442 TCX Red Ochre. Приглушённый кирпич — тревога без крика.
    static let redOchre = "#9B4A3C"

    /// 14-3812 TCX Pastel Lilac.
    static let pastelLilac = "#B4A8D0"

    /// 16-0947 TCX Bright Gold.
    static let brightGold = "#D2A44B"

    /// 19-5421 TCX Aventurine. Тёмная зелень, читается как «живое».
    static let aventurine = "#1D5744"

    // MARK: - Нейтрали

    /// 墨 — тушь. Основной фон, почти чёрный, но не чистый: чистый чёрный
    /// на экране выглядит дырой, а не глубиной.
    static let sumi = "#0B0B0B"

    /// Приподнятая поверхность. Отличается от фона на пару процентов —
    /// достаточно, чтобы глаз увидел слой, и мало, чтобы это стало границей.
    static let sumiRaised = "#151515"

    /// Тёплый не-белый. Чистый белый на чёрном бьёт по глазам.
    static let washi = "#EDEAE3"

    /// Второстепенный текст.
    static let ash = "#6E6B66"

    /// Тончайшая линия. Заменяет рамки: в этой системе границ почти нет.
    static let hairline = "#242320"
}
