//  Шкала отступов.
//
//  Дисциплина пространства держится не на вкусе, а на том, что расстояний
//  в интерфейсе ровно шесть. Число между шагами не берётся: если 16 мало,
//  а 32 много — значит, элементы сгруппированы неправильно.
//

import CoreGraphics

enum Space {

    /// Волосок. Толщина линии, зазор внутри плотной группы.
    static let hair: CGFloat = 2

    /// Внутри одного элемента: текст и его подпись.
    static let tight: CGFloat = 8

    /// Между элементами одной группы.
    static let step: CGFloat = 16

    /// Между группами.
    static let room: CGFloat = 24

    /// Поля экрана.
    static let margin: CGFloat = 32

    /// 間 — пауза. Пустота как элемент композиции, а не как остаток места.
    static let ma: CGFloat = 64
}
