//
//  Явная «расписка» перед компилятором для значений, которые не Sendable,
//  но по контракту фреймворка безопасно передаются через границу изоляции.
//
//  Использовать только там, где безопасность гарантирована внешним API:
//  каждое применение — осознанное решение, а не способ заглушить варнинг.
//

/// Обёртка, переносящая не-`Sendable` значение через границу изоляции.
struct UncheckedSendableBox<Value>: @unchecked Sendable {

    let value: Value

    init(_ value: Value) {
        self.value = value
    }
}
