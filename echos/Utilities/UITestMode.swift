//
//  UITestMode.swift
//  echos
//
//  Запуск из UI-тестов: экраны с содержимым, без устройств рядом и без сети.
//
//  UI-тест управляет приложением снаружи, отдельным процессом, и подменить
//  транспорт или хранилище, как в модульном тесте, не может. Поэтому он
//  просит об этом аргументом запуска `-UITests`, а приложение берёт
//  демонстрационный транспорт с готовыми собеседниками и хранилище в
//  памяти — настоящие данные на симуляторе не трогаются.
//
//  Только в Debug: в выпускной сборке флага нет, и `isActive` всегда false.
//

import Foundation

enum UITestMode {
    static var isActive: Bool {
        #if DEBUG
        ProcessInfo.processInfo.arguments.contains("-UITests")
        #else
        false
        #endif
    }
}
